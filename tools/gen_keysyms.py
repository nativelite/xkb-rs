#!/usr/bin/env python3
"""Regenerate src/keysym_table.rs (dev-only, stdlib Python, not part of the build).

Two sources of facts, no code:

* every keysym name and its number, from the `#define XKB_KEY_<name> <value>`
  lines of libxkbcommon's `xkbcommon-keysyms.h` (aliases included; the library
  itself can only report one name per value);
* the canonical name of each value and its Unicode code point, by asking the
  installed reference library (`libxkbcommon.so.0`) for every keysym in
  0..0x100000 and 0x10000000..0x10090000, and for every header value outside
  those ranges.

Run on Linux, with the header of the same version as the installed library:

    python3 tools/gen_keysyms.py path/to/xkbcommon-keysyms.h src/keysym_table.rs
"""
from __future__ import annotations

import ctypes
import re
import sys

DEFINE = re.compile(r"^#define XKB_KEY_([A-Za-z0-9_]+)\s+(0x[0-9a-fA-F]+|_EVDEVK\((0x[0-9a-fA-F]+)\))")
RANGES = ((0, 0x100000), (0x10000000, 0x10090000))


def header_names(path: str) -> list[tuple[str, int]]:
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = DEFINE.match(line)
            if not m:
                continue
            value = 0x10081000 + int(m.group(3), 16) if m.group(3) else int(m.group(2), 16)
            out.append((m.group(1), value))
    return out


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    lib = ctypes.CDLL("libxkbcommon.so.0")
    lib.xkb_keysym_get_name.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]
    lib.xkb_keysym_get_name.restype = ctypes.c_int
    lib.xkb_keysym_from_name.argtypes = [ctypes.c_char_p, ctypes.c_int]
    lib.xkb_keysym_from_name.restype = ctypes.c_uint32
    lib.xkb_keysym_to_utf32.argtypes = [ctypes.c_uint32]
    lib.xkb_keysym_to_utf32.restype = ctypes.c_uint32
    buf = ctypes.create_string_buffer(128)

    names = header_names(argv[1])
    by_name = dict(names)
    assert len(by_name) == len(names), "a name defined twice"
    for name, value in names:
        got = lib.xkb_keysym_from_name(name.encode(), 0)
        assert got == value, f"{name}: header {value:#x}, library {got:#x}"

    canonical: dict[int, str] = {}
    ucs: dict[int, int] = {}
    scan = [ks for lo, hi in RANGES for ks in range(lo, hi)]
    scan += sorted(v for v in set(by_name.values()) if not any(lo <= v < hi for lo, hi in RANGES))
    if True:
        for ks in scan:
            n = lib.xkb_keysym_get_name(ks, buf, 128)
            if n > 0:
                name = buf.value.decode()
                if by_name.get(name) == ks:
                    canonical[ks] = name
                else:
                    assert name.startswith("0x") or name.startswith("U"), (hex(ks), name)
            cp = lib.xkb_keysym_to_utf32(ks)
            latin1 = 0x20 <= ks <= 0x7E or 0xA0 <= ks <= 0xFF
            direct = 0x01000000 <= ks <= 0x0110FFFF
            if cp and not latin1 and not direct:
                ucs[ks] = cp
    assert set(canonical) == set(by_name.values()), "a header value the library does not name"

    out = [
        "//! Keysym names, numbers and Unicode code points. GENERATED by",
        "//! tools/gen_keysyms.py from the keysym definitions of libxkbcommon",
        "//! 1.6.0 (see THIRD-PARTY-NOTICES.md); do not edit by hand.",
        "",
        "/// Every keysym name and its number, sorted by name (byte order).",
        "#[rustfmt::skip]",
        f"pub(crate) static BY_NAME: [(&str, u32); {len(names)}] = [",
    ]
    for name, value in sorted(names, key=lambda nv: nv[0].encode()):
        out.append(f'    ("{name}", {value:#06x}),')
    out += [
        "];",
        "",
        "/// The canonical name of every named keysym, sorted by number.",
        "#[rustfmt::skip]",
        f"pub(crate) static BY_VALUE: [(u32, &str); {len(canonical)}] = [",
    ]
    for value in sorted(canonical):
        out.append(f'    ({value:#06x}, "{canonical[value]}"),')
    out += [
        "];",
        "",
        "/// Keysym to Unicode code point, sorted by keysym, for the keysyms that",
        "/// are neither Latin-1 (the keysym is the code point) nor in the",
        "/// directly encoded range (0x01000000 + code point).",
        "#[rustfmt::skip]",
        f"pub(crate) static TO_UCS: [(u32, u32); {len(ucs)}] = [",
    ]
    for ks in sorted(ucs):
        out.append(f"    ({ks:#06x}, {ucs[ks]:#06x}),")
    out += ["];", ""]
    with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{len(names)} names, {len(canonical)} values, {len(ucs)} code points")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
